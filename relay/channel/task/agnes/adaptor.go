// 任务提交走 OpenAI Videos 兼容端点（body 原样透传，mode/first_frame/
// last_frame/images/audios 等扩展字段由 Agnes 上游校验）；任务查询走
// Agnes 专属的 /agnesapi?video_id=<VIDEO_ID>&model_name=<MODEL>，这是
// 官方文档对 text/keyframe/reference 全部模式推荐的轮询方式，且
// keyframe/reference 模式必须带 model_name。
// 文档: https://www.agnes-ai.com/zh-Hans/docs/agnes-video-25

// ============================
// Request / Response structures
// ============================

type responseTask struct {
	ID          string `json:"id"`
	TaskID      string `json:"task_id,omitempty"`
	VideoID     string `json:"video_id,omitempty"` // /agnesapi 轮询所需的视频 ID
	Object      string `json:"object"`
	Model       string `json:"model"`
	Status      string `json:"status"`
	Progress    int    `json:"progress"`
	CreatedAt   int64  `json:"created_at"`
	CompletedAt int64  `json:"completed_at,omitempty"`
	ExpiresAt   int64  `json:"expires_at,omitempty"`
	Seconds     string `json:"seconds,omitempty"`
	Size        string `json:"size,omitempty"`
	URL         string `json:"url,omitempty"` // 任务完成后可交付的视频地址
	Error       *struct {
		Message string `json:"message"`
		Code    string `json:"code"`
	} `json:"error,omitempty"`
}

